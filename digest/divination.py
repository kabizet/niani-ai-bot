def match_spread(question):
    """按问题关键词匹配牌阵，返回牌阵 dict；没匹配到就返回默认三张牌。"""
    q = (question or "").lower()
    for sp in SPREADS:
        if not sp["tags"]:
            continue
        if any(t in q for t in sp["tags"]):
            return sp
    return SPREADS[0]


def draw_spread(question, picks, spread):
    """用三个数字做随机种子，按牌阵抽 n 张牌（带正逆位）。"""
    deck = list(DECK)
    random.seed((int(picks[0]) * 1000 + int(picks[1]) * 10 + int(picks[2])) % 2 ** 31)
    random.shuffle(deck)
    n = spread["n"]
    out = []
    for i in range(n):
        name, up, rev = deck[i % 78]
        reversed_ = random.random() < 0.5
        out.append({
            "no": i + 1,
            "name": name,
            "pos": "逆位" if reversed_ else "正位",
            "meaning": rev if reversed_ else up,
        })
    return out


def spread_text(question, cards, spread):
    """给模型看的原始材料（带牌阵位置）。"""
    pos = spread["positions"]
    lines = ["问题：%s" % question, "牌阵：%s（共 %d 张）" % (spread["name"], spread["n"]), ""]
    for i, c in enumerate(cards):
        pname = pos[i] if i < len(pos) else "第%d位" % (i + 1)
        lines.append("%s：%s · %s —— %s" % (pname, c["name"], c["pos"], c["meaning"]))
    return "\n".join(lines)


