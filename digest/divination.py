_GUA_BY_PAIR = {(g[1], g[2]): g for g in ICHING}


def iching_draw(picks):
    """梅花易数式数字起卦。picks: 三个数字（1-8、1-8、1-6 附近都行，取余）。
    返回：本卦、变卦、动爻。"""
    a = int(picks[0]) % 8 or 8
    b = int(picks[1]) % 8 or 8
    dong = int(picks[2]) % 6 or 6
    order = ["乾", "兑", "离", "震", "巽", "坎", "艮", "坤"]
    shang = order[a - 1]
    xia = order[b - 1]
    ben = _GUA_BY_PAIR.get((shang, xia))
    if not ben:
        return None
    # 变卦：动爻翻转（1-3 在下卦，4-6 在上卦）
    xia_bits = list(_BAGUA_BITS[xia])
    shang_bits = list(_BAGUA_BITS[shang])
    if dong <= 3:
        idx = dong - 1
        xia_bits[idx] = 1 - xia_bits[idx]
    else:
        idx = dong - 4
        shang_bits[idx] = 1 - shang_bits[idx]
    nx = _BITS2GUA.get(tuple(xia_bits), xia)
    ns = _BITS2GUA.get(tuple(shang_bits), shang)
    bian = _GUA_BY_PAIR.get((ns, nx))
    return {
        "ben": {"name": ben[0], "shang": shang, "xia": xia, "meaning": ben[3]},
        "bian": {"name": bian[0], "meaning": bian[3]} if bian else None,
        "dong": dong,
    }


def iching_text(result, question):
    """给模型看的原始材料。"""
    b = result["ben"]
    lines = ["问题：%s" % question,
             "起卦得：%s卦（%s，上%s下%s）" % (b["name"], b["meaning"], b["shang"], b["xia"]),
             "动爻在第 %d 爻。" % result["dong"]]
    if result.get("bian"):
        bb = result["bian"]
        lines.append("变卦为：%s卦（%s）" % (bb["name"], bb["meaning"]))
    return "\n".join(lines)
