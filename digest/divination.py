def lucky(qq, birthday, day=None):
    """星座 + 幸运色 + 幸运数字 + 一句一言。"""
    md = parse_birthday(birthday)
    if not md:
        return None
    year, month, mday = md
    day = day or datetime.date.today()
    sign = sign_of(month, mday)
    row = next(s for s in SIGNS if s[0] == sign)
    nums, colors = row[3], row[4]
    num = _pick(nums, "%s-%s-num" % (qq, day))
    color = _pick(colors, "%s-%s-color" % (qq, day))

    return "✨ 幸运色　%s\n🔢 吉利数字　%d\n「%s」" % (
        color, num, quote("%s-%s" % (qq, day)))


