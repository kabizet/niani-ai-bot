    """picks: 1-78 的三个数字。返回三张牌（含正逆位）。"""
    deck = list(DECK)
    random.shuffle(deck)
    out = []
    for n in picks:
        name, up, rev = deck[(int(n) - 1) % 78]
        reversed_ = random.random() < 0.5
        out.append({
            "no": int(n),
            "name": name,
            "pos": "逆位" if reversed_ else "正位",
            "meaning": rev if reversed_ else up,
        })
    return out


