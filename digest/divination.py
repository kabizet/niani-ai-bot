def sign_of(month, day):
    """按日期算星座（切分点：每个星座的第一天）。"""
    sign = "摩羯座"
    for m, d, name in CUTOFFS:
        if (month, day) >= (m, d):
            sign = name
        else:
            break
    return sign


def parse_birthday(s):
    """支持 010712(2001-07-12) / 20010712 / 0712 / 07-12。

    返回 (year, month, day)；四位的只有月日，year 为 None。
    """
    s = re.sub(r"[^0-9]", "", str(s or ""))
    y = None
    if len(s) == 8:
        y, s = int(s[:4]), s[4:]
    elif len(s) == 6:
        yy = int(s[:2])
        y = 2000 + yy if yy <= 30 else 1900 + yy
        s = s[2:]
    if len(s) != 4:
        return None
    m, d = int(s[:2]), int(s[2:])
    if not (1 <= m <= 12 and 1 <= d <= 31):
        return None
    return y, m, d


